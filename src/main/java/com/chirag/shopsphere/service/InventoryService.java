package com.chirag.shopsphere.service;

import com.chirag.shopsphere.dto.InventoryTransactionResponse;
import com.chirag.shopsphere.dto.PageResponse;
import com.chirag.shopsphere.dto.StockAdjustmentRequest;
import com.chirag.shopsphere.entity.InventoryTransaction;
import com.chirag.shopsphere.entity.Product;
import com.chirag.shopsphere.entity.TransactionType;
import com.chirag.shopsphere.exception.BadRequestException;
import com.chirag.shopsphere.exception.ResourceNotFoundException;
import com.chirag.shopsphere.repository.InventoryTransactionRepository;
import com.chirag.shopsphere.repository.ProductRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
@RequiredArgsConstructor
@Transactional(readOnly = true)
public class InventoryService {

    private final InventoryTransactionRepository inventoryTransactionRepository;
    private final ProductRepository productRepository;

    public PageResponse<InventoryTransactionResponse> listTransactions(Pageable pageable) {
        Page<InventoryTransactionResponse> page = inventoryTransactionRepository.findAll(pageable)
                .map(InventoryTransactionResponse::fromEntity);
        return PageResponse.from(page);
    }

    public PageResponse<InventoryTransactionResponse> listTransactionsByProduct(Long productId, Pageable pageable) {
        if (!productRepository.existsById(productId)) {
            throw new ResourceNotFoundException("Product", "id", productId);
        }
        Page<InventoryTransactionResponse> page = inventoryTransactionRepository.findByProductIdOrderByCreatedAtDesc(productId, pageable)
                .map(InventoryTransactionResponse::fromEntity);
        return PageResponse.from(page);
    }

    public InventoryTransactionResponse getTransactionById(Long id) {
        InventoryTransaction tx = inventoryTransactionRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("InventoryTransaction", "id", id));
        return InventoryTransactionResponse.fromEntity(tx);
    }

    /**
     * Dedicated operation that ensures stock update and audit ledger are atomically committed together.
     * Prevents arbitrary audit creation without corresponding physical inventory modification.
     */
    @Transactional
    public InventoryTransactionResponse recordStockAdjustment(StockAdjustmentRequest request) {
        if (request.getType() == TransactionType.ORDER || request.getType() == TransactionType.CANCELLATION) {
            throw new BadRequestException("ORDER and CANCELLATION inventory transactions are automatically generated by the order lifecycle");
        }

        Product product = productRepository.findByIdWithLock(request.getProductId())
                .orElseThrow(() -> new ResourceNotFoundException("Product", "id", request.getProductId()));

        int newStock = product.getStockQuantity() + request.getQuantityChange();
        if (newStock < 0) {
            throw new BadRequestException(String.format(
                    "Stock adjustment would result in negative stock. Current: %d, Change: %d",
                    product.getStockQuantity(), request.getQuantityChange()));
        }

        product.setStockQuantity(newStock);
        productRepository.save(product);

        InventoryTransaction tx = InventoryTransaction.builder()
                .product(product)
                .quantityChange(request.getQuantityChange())
                .type(request.getType())
                .reference(request.getReference() != null ? request.getReference() : "Manual stock adjustment")
                .build();

        InventoryTransaction saved = inventoryTransactionRepository.save(tx);
        return InventoryTransactionResponse.fromEntity(saved);
    }
}
